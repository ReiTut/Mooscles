    private fun section(
        equipment: Gear,
        convention: Load = Load.TOTAL_LOAD,
        block: CatalogSection.() -> Unit
    ): List<Exercise> = CatalogSection(equipment, convention).apply(block).items.toList()

    private class CatalogSection(
        private val equipment: Gear,
        private val defaultConvention: Load
    ) {
        val items = mutableListOf<Exercise>()

        fun exercise(
            stableId: String,
            name: String,
            muscle: Muscle,
            convention: Load = defaultConvention
        ) {
            items += Exercise(
                id = "catalog_$stableId",
                name = name,
                muscle = muscle,
                equipment = equipment,
                convention = convention,
                custom = false
            )
        }
    }
